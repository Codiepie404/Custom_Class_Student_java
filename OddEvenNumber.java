import java.util.*;

public class OddEvenNumber {
    public static void main(String[] args) {
        System.out.println("Hey There Rakib here.!");
        System.out.println("Odd Number Print: ");
        for(int i=0;i<=15;i++){
            if(i%2==0){
                System.out.println("Even Number: "+i);
            }
        }
        for(int j=0;j<=15;j++){
            if(j%2==1){
                System.out.println("Odd Number: "+j);
            }
        }
    }
}
